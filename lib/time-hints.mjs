/**
 * 时间表达式预筛：判断一条聊天消息「值不值得送进模型」。
 *
 * 为什么需要它：一个学期下来，全校几十个群可以轻松堆出十几万条消息，
 * 其中真正带时间约束的不到 1%。全量送模型既慢又贵（一条 5000 字切片
 * 送一次，几十个群就是上百次调用）。先用正则把「提到时间 + 提到要做什么」
 * 的消息挑出来，再送模型，能砍掉九成以上的调用量。
 *
 * 注意分工：正则**只负责筛**，不负责判断。它筛出来的东西里仍有大量
 * 「明天一起去吃饭」这类闲聊，真正的取舍交给模型。宁可多筛不能漏筛。
 */

/** 时间信号：日期、星期、相对日、钟点、时间区间 */
const TIME_PATTERNS = [
  // 2026-11-12 / 2026/11/12 / 2026年11月12日 / 11月12日 / 11.12 / 11/12
  /(?:\d{4}\s*[-/年.]\s*)?\d{1,2}\s*[-/月.]\s*\d{1,2}\s*[日号]?/,
  // 周一…周日 / 星期一 / 礼拜天 / 下周三 / 这周五
  /(?:这|本|下|下一个?|上)?\s*(?:周|星期|礼拜)\s*[一二三四五六日天1-7]/,
  // 今天 明天 后天 大后天 今晚 明晚 昨天
  /(?:今|明|后|昨|前)\s*[天日晚早中午晨]/,
  // 本周 下周 这周 周末 月初 月底 月末
  /(?:这|本|下|上)?\s*(?:周|星期|礼拜)(?:末|初|底)?(?!\s*[一二三四五六日天])/,
  // 19:00 / 19：00
  /\d{1,2}\s*[:：]\s*\d{2}/,
  // 七点 / 7点 / 19点半 / 三点半 / 9点30
  /\d{1,2}\s*点(?:半|整|\d{1,2}\s*分)?/,
  // 中文数字钟点：七点、九点半、两点
  /[一二三四五六七八九十]{1,2}\s*点(?:半|整|\d{1,2}\s*分)?/,
  // 第10周 / 第 3 周 / 第二周
  /第\s*[0-9一二三四五六七八九十]{1,3}\s*周/,
  // 截止 之前 以前 前提交
  /(?:\d+\s*(?:天|小时|分钟)\s*(?:内|后)|截止|之前|以前|前\s*(?:提交|完成|上交|上传))/,
];

/** 动作信号：这件事要人做点什么。只有时间没动作的多半是闲聊 */
const ACTION_PATTERNS = [
  /截止|ddl|DDL|deadline/i,
  /提交|上交|上传|交(?:作业|材料|表|报告|论文|作品)|发送至|发到|发给我/,
  // 裸「交」：排除交流/交往/交通/交易/交换这类词
  /(?<![交发])交(?!流|往|通|易|换|替|际|互|给)/,
  /报名|预约|抢|选课|退课|缴费|注册|签到|打卡|确认|填写|填报/,
  /考试|测验|小测|期中|期末|补考|重修|四六级|机考|笔试|面试/,
  /体测|体检|早操|跑步|体育|测试/,
  /开会|会议|例会|组会|班会|座谈|培训|讲座|报告会|宣讲|答辩|汇报|面试/,
  // 教务动作：停课调课这类「时间有变化」的通知往往不含提交/到场字样
  /停课|调课|补课|加课|开课|上课|放假|收假|调休|取消|改期|延期|提前|推迟|请假/,
  /集合|到场|准时|务必|必须|统一|集中|出发|领取|交表/,
  /活动|晚会|比赛|竞赛|大赛|演出|展览|志愿|义工|招聘|实习/,
  /通知|安排|名单|公示/,
];

/** 强时间信号：出现具体日期或钟点时，即使没有动作词也值得看一眼 */
const STRONG_TIME = [
  /\d{4}\s*[-/年.]\s*\d{1,2}\s*[-/月.]\s*\d{1,2}/,
  /\d{1,2}\s*月\s*\d{1,2}\s*[日号]/,
  /\d{1,2}\s*[:：]\s*\d{2}/,
  // 「七点半」「三点整」：有明确钟点的消息本身就值钱，不该因为没写「开会」被漏掉
  /[一二三四五六七八九十]{1,2}\s*点(?:半|整)/,
  /第\s*[0-9一二三四五六七八九十]{1,3}\s*周/,
];

function anyMatch(patterns, text) {
  for (const re of patterns) if (re.test(text)) return true;
  return false;
}

/**
 * 这条消息是否值得送模型。
 * 规则：必须含时间信号，且（含动作信号 或 含强时间信号）。
 */
export function hasTimeHint(text) {
  const s = String(text || "");
  if (s.length < 6) return false;
  if (!anyMatch(TIME_PATTERNS, s)) return false;
  return anyMatch(ACTION_PATTERNS, s) || anyMatch(STRONG_TIME, s);
}

/**
 * 严格版：必须有「具体日期 / 具体钟点 / 明确截止」。
 *
 * 为什么还要分一档：全量扫群时，家教群、闲置群、门店会员群会大量出现
 * 「明天下午三点来接孩子」这种句子——时间齐全、动作也有，普通预筛全部放行，
 * 一个 800 条的群能过 680 条，等于没筛，模型调用成本直接爆掉。
 *
 * 这类群不是没有价值（家长群也可能发停课通知），所以不排除，只提高门槛：
 * 必须给出能落到日历上的具体时刻，而不是「明天」这种相对词。
 */
export function hasStrongTimeHint(text) {
  const s = String(text || "");
  if (s.length < 6) return false;
  if (anyMatch(STRONG_TIME, s)) return true;
  return /截止|之前|以前|前提交|前完成|ddl|deadline/i.test(s);
}

/** 只判断有没有时间表达，不看内容类型（供「时间轴」模式用，更宽松） */
export function hasAnyTime(text) {
  for (const re of TIME_PATTERNS) if (re.test(String(text || ""))) return true;
  return false;
}

/** 从文本里抽出所有时间片段，用于给模型做锚点提示（可选） */
export function timeFragments(text) {
  const out = new Set();
  for (const re of TIME_PATTERNS) {
    const g = new RegExp(re.source, re.flags.includes("g") ? re.flags : re.flags + "g");
    let m;
    while ((m = g.exec(String(text || "")))) {
      out.add(m[0].trim());
      if (out.size > 12) return [...out];
    }
  }
  return [...out];
}
