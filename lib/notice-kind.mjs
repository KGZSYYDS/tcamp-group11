/**
 * 判定一条通知的内容类型。
 * 没有任何规则命中时返回 "other" —— 交给上层按「不确定就不打扰」处理。
 *
 * 注意：这里**不看正文**。试过用「正文里有报名/申请就当成机会」，
 * 结果「篮球场暂停使用」因为正文提到申请流程被判成机会 —— 正文噪声太大，
 * 而误判方向又恰好是「本来该藏起来的被推上来」，代价比漏判高得多。
 *
 * @param {string} title
 */
export function noticeKindOf(title) {
  const t = norm(title);
  if (!t) return "other";

  let best = "other";
  let bestScore = 0;
  for (const [kind, re, weight] of RULES) {
    if (weight <= bestScore) continue;
    if (re.test(t)) {
      best = kind;
      bestScore = weight;
    }
  }
  return best;
}

